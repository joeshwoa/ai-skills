#!/usr/bin/env python3
"""
voiceover.py — generate OFF-SCREEN narration only.

Policy (see references/audio.md): any voice that belongs to a character
on screen is generated by the video model itself, inside the clip, with
lip-sync. External TTS is used for exactly one thing — a narrator the
audience never sees. So this script never tries to sync to lips; it
produces clean narration files with measured durations, and assemble.py
places them on the timeline.

Providers:
  gemini      Gemini API TTS. Same 30 voice names Flow uses (Charon, Kore,
              Achird, Sulafat...), so a narrator can match a Flow voice.
              Needs GEMINI_API_KEY (free key from Google AI Studio).
  elevenlabs  ElevenLabs TTS. Needs ELEVENLABS_API_KEY and a voice id.
              Free plan: ~10k credits/month, non-commercial, attribution
              required — say so before using it for a client.

USAGE
    # one line
    python3 voiceover.py --provider gemini --voice Charon \
        --style "Narrate in warm, natural Egyptian Arabic, unhurried, like a documentary" \
        --text "في كل سنة، الأرض بتسخن شوية..." --out vo/n01.wav --max-seconds 6

    # a script of lines -> one file per line + timing sheet
    python3 voiceover.py --provider gemini --voice Charon --script vo_script.json --outdir vo/

    # show the exact request without calling anything (no key needed)
    python3 voiceover.py ... --dry-run

vo_script.json: [{"id": "N01", "text": "...", "style": "optional per-line direction",
                  "max_seconds": 6.0}]
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
import wave

GEMINI_DEFAULT_MODEL = "gemini-2.5-flash-preview-tts"
GEMINI_URL = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
ELEVEN_URL = "https://api.elevenlabs.io/v1/text-to-speech/{voice}?output_format=mp3_44100_128"
ELEVEN_DEFAULT_MODEL = "eleven_multilingual_v2"
PCM_RATE = 24000  # Gemini TTS returns 24 kHz, 16-bit, mono PCM


def gemini_request(text: str, voice: str, style: str | None, model: str) -> tuple[str, dict]:
    prompt = f"{style.strip()}:\n{text}" if style else text
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {
            "responseModalities": ["AUDIO"],
            "speechConfig": {"voiceConfig": {"prebuiltVoiceConfig": {"voiceName": voice}}},
        },
    }
    return GEMINI_URL.format(model=model), body


def eleven_request(text: str, voice_id: str, model: str) -> tuple[str, dict]:
    return ELEVEN_URL.format(voice=voice_id), {"text": text, "model_id": model}


def write_pcm_wav(pcm: bytes, path: str, rate: int = PCM_RATE) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(pcm)


def post(url: str, body: dict, headers: dict) -> bytes:
    req = urllib.request.Request(url, data=json.dumps(body).encode("utf-8"),
                                 headers={"Content-Type": "application/json", **headers})
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return r.read()
    except urllib.error.HTTPError as e:
        detail = e.read().decode("utf-8", "replace")[:600]
        raise SystemExit(f"TTS request failed: HTTP {e.code}\n{detail}")


def duration(path: str) -> float | None:
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                        "-of", "csv=p=0", path], capture_output=True, text=True)
    try:
        return round(float(r.stdout.strip()), 2)
    except ValueError:
        return None


def synth(args, text: str, style: str | None, out: str) -> dict:
    if args.provider == "gemini":
        url, body = gemini_request(text, args.voice, style, args.model or GEMINI_DEFAULT_MODEL)
        if args.dry_run:
            return {"dry_run": True, "url": url, "body": body, "out": out}
        key = os.environ.get("GEMINI_API_KEY")
        if not key:
            raise SystemExit("GEMINI_API_KEY is not set. Get a free key at "
                             "https://aistudio.google.com/apikey and export it — "
                             "never paste it into a file in this repo.")
        raw = post(url, body, {"x-goog-api-key": key})
        data = json.loads(raw)
        try:
            b64 = data["candidates"][0]["content"]["parts"][0]["inlineData"]["data"]
        except (KeyError, IndexError):
            raise SystemExit(f"Unexpected Gemini response: {json.dumps(data)[:600]}")
        if not out.lower().endswith(".wav"):
            out = os.path.splitext(out)[0] + ".wav"
        write_pcm_wav(base64.b64decode(b64), out)
    else:
        if not args.voice_id:
            raise SystemExit("--voice-id is required for ElevenLabs (from your ElevenLabs voice library)")
        url, body = eleven_request(text, args.voice_id, args.model or ELEVEN_DEFAULT_MODEL)
        if args.dry_run:
            return {"dry_run": True, "url": url, "body": body, "out": out}
        key = os.environ.get("ELEVENLABS_API_KEY")
        if not key:
            raise SystemExit("ELEVENLABS_API_KEY is not set.")
        audio = post(url, body, {"xi-api-key": key, "Accept": "audio/mpeg"})
        if not out.lower().endswith(".mp3"):
            out = os.path.splitext(out)[0] + ".mp3"
        os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
        with open(out, "wb") as f:
            f.write(audio)
    return {"out": out, "seconds": duration(out)}


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate off-screen narration (voice-over).")
    ap.add_argument("--provider", choices=["gemini", "elevenlabs"], required=True)
    ap.add_argument("--voice", default="Charon", help="Gemini voice name (see capabilities.json)")
    ap.add_argument("--voice-id", help="ElevenLabs voice id")
    ap.add_argument("--model", help="override the TTS model id")
    ap.add_argument("--style", help="natural-language delivery direction (Gemini)")
    ap.add_argument("--text")
    ap.add_argument("--out", default="vo.wav")
    ap.add_argument("--max-seconds", type=float, help="the window this line must fit")
    ap.add_argument("--script", help="JSON list of lines")
    ap.add_argument("--outdir", default="vo")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    jobs = []
    if args.script:
        with open(args.script, encoding="utf-8") as f:
            for ln in json.load(f):
                jobs.append((ln["id"], ln["text"], ln.get("style") or args.style,
                             os.path.join(args.outdir, f"{ln['id']}.wav"), ln.get("max_seconds")))
    elif args.text:
        jobs.append(("line", args.text, args.style, args.out, args.max_seconds))
    else:
        ap.error("give --text or --script")

    sheet, problems = [], 0
    for jid, text, style, out, maxs in jobs:
        res = synth(args, text, style, out)
        if res.get("dry_run"):
            print(json.dumps(res, ensure_ascii=False, indent=1))
            continue
        secs = res.get("seconds")
        flag = ""
        if maxs and secs and secs > maxs:
            flag = f"  X {secs}s > window {maxs}s — shorten the line, do not speed the audio up"
            problems += 1
        print(f"{jid}: {res['out']}  {secs}s{flag}")
        sheet.append({"id": jid, "file": res["out"], "seconds": secs, "max_seconds": maxs})

    if sheet:
        os.makedirs(args.outdir, exist_ok=True)
        path = os.path.join(args.outdir, "timing.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(sheet, f, ensure_ascii=False, indent=1)
        print(f"timing sheet -> {path}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
